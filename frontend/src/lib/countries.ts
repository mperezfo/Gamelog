/** The flag of a two-letter code: the two regional indicator letters it is
 * written with, which Emoji draws as the flag's image. */
export function flagOf(code: string): string {
  return Array.from(code.toUpperCase(), (letter) => String.fromCodePoint(0x1f1e6 + letter.charCodeAt(0) - 65)).join('')
}

let names: Intl.DisplayNames | null | undefined

/** The country's name in English ("Japan"), or the code itself where the
 * browser cannot name it. */
export function countryName(code: string): string {
  if (names === undefined) {
    try {
      names = new Intl.DisplayNames(['en'], { type: 'region' })
    } catch {
      names = null
    }
  }
  return names?.of(code) ?? code
}
